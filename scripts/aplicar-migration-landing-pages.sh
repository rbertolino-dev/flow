#!/bin/bash
# Script para aplicar migration de Landing Pages automaticamente

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
cd "$PROJECT_DIR"

MIGRATION_FILE="supabase/migrations/20260123000001_create_landing_pages.sql"

echo "🚀 Aplicando migration de Landing Pages..."
echo "📄 Arquivo: $MIGRATION_FILE"
echo ""

# Ler conteúdo da migration
if [ ! -f "$MIGRATION_FILE" ]; then
    echo "❌ Arquivo não encontrado: $MIGRATION_FILE"
    exit 1
fi

SQL_CONTENT=$(cat "$MIGRATION_FILE")

# Tentar aplicar via Supabase CLI (método mais simples)
echo "📤 Tentando aplicar via Supabase CLI..."
if command -v supabase &> /dev/null; then
    # Criar migration temporária e aplicar
    TEMP_DIR=$(mktemp -d)
    cp "$MIGRATION_FILE" "$TEMP_DIR/"
    
    # Tentar aplicar via db push
    if echo "y" | supabase db push --include-all 2>&1 | grep -qE "Successfully|Applied|completed"; then
        echo "✅ Migration aplicada via Supabase CLI!"
        rm -rf "$TEMP_DIR"
        exit 0
    else
        echo "⚠️  Supabase CLI não conseguiu aplicar automaticamente"
    fi
    rm -rf "$TEMP_DIR"
fi

# Se chegou aqui, mostrar instruções
echo ""
echo "📋 Migration precisa ser aplicada manualmente:"
echo ""
echo "Opção 1: Via Supabase Dashboard"
echo "   1. Acesse: https://supabase.com/dashboard/project/ogeljmbhqxpfjbpnbwog/sql"
echo "   2. Cole o conteúdo do arquivo: $MIGRATION_FILE"
echo "   3. Execute o SQL"
echo ""
echo "Opção 2: Via Supabase CLI (se projeto estiver linkado)"
echo "   supabase db push"
echo ""
echo "📄 Conteúdo da migration:"
